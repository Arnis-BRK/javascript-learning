/*

&& → todas precisam ser verdadeiras
|| → pelo menos uma precisa ser verdadeira
!  → inverte o resultado

true && true    // true
true && false   // false
false && true   // false
false && false  // false
- Só dá true quando as duas condições são verdadeiras.


true || true    // true
true || false   // true
false || true   // true
false || false  // false
- Basta uma das condições ser verdadeira.

!true   // false
!false  // true

*/