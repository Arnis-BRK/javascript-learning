let x = 5;

console.log("The result of", x, "+ 5 is:", x + 5);
console.log("The result of", x, "- 5 is:", x - 5);
console.log("The result of", x, "* 5 is:", x * 5);
console.log("The result of", x, "/ 5 is:", x / 5);
console.log("The result of", x, "% 5 is:", x % 5);
console.log("The result of", x, "** 5 is:", x ** 5);
console.log("The decrementation of", x, "is:", --x);
console.log("The incrementation of the previous value", x,"by 1 is:", ++x);

